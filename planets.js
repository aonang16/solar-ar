function hash(i, j, k, s) {
  let h = Math.imul(i, 374761393) ^ Math.imul(j, 668265263) ^ Math.imul(k, 1274126177) ^ Math.imul(s, 1103515245);
  h = Math.imul(h ^ (h >>> 13), 1274126177); h ^= h >>> 16;
  return (h >>> 0) / 4294967296;
}
const sm = t => t * t * (3 - 2 * t);
function noise3(x, y, z, s) {
  const xi = Math.floor(x), yi = Math.floor(y), zi = Math.floor(z);
  const u = sm(x - xi), v = sm(y - yi), w = sm(z - zi);
  const L = (a, b, t) => a + (b - a) * t;
  const c = (dx, dy, dz) => hash(xi + dx, yi + dy, zi + dz, s);
  return L(L(L(c(0,0,0), c(1,0,0), u), L(c(0,1,0), c(1,1,0), u), v),
           L(L(c(0,0,1), c(1,0,1), u), L(c(0,1,1), c(1,1,1), u), v), w);
}
function fbm(x, y, z, oct, s) {
  let a = .5, f = 1, sum = 0, norm = 0;
  for (let o = 0; o < oct; o++) { sum += a * noise3(x * f, y * f, z * f, s + o); norm += a; a *= .5; f *= 2; }
  return sum / norm;
}
function ridged(x, y, z, oct, s) {
  let a = .5, f = 1, sum = 0, norm = 0;
  for (let o = 0; o < oct; o++) { let v = 1 - Math.abs(noise3(x * f, y * f, z * f, s + o) * 2 - 1); sum += a * v * v; norm += a; a *= .5; f *= 2.1; }
  return sum / norm;
}
